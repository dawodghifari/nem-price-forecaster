"""Day 1 exit condition: confirm the MMS layout against real files.

The plan's rule is not to trust an assumed schema, so this script downloads
live files and answers the questions the rest of the build depends on:

1. What tables are actually inside DISPATCHIS and P5MIN, and what columns?
2. Does SETTLEMENTDATE label the start or the end of its interval? Getting this
   backwards shifts every price lag by five minutes, in the direction that
   makes the model look better than it is.
3. Does P5MIN carry both a run time and a target interval, which the benchmark
   join needs? How long after the run time does the file actually appear?
4. Does DISPATCH.PRICE carry an INTERVENTION flag, and both RRP and ROP? If so,
   a file can hold two prices for one interval and they must not be mixed.
5. Do the parsed 5-minute prices reconcile against AEMO's separately published
   aggregated price series? This is the only check that proves the right
   column was read rather than a plausible neighbour.

Run it with `make verify`. It writes docs/day1_format_findings.md and prints a
summary. Nothing here touches Postgres, so it works before the database is up.
"""

from __future__ import annotations

import argparse
import io
import logging
import statistics
import sys
from datetime import datetime, timedelta, timezone
from pathlib import Path

import httpx
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from nemfc.config import REPO_ROOT, load_settings
from nemfc.mms import MMSFile, read_mms_zip_single
from nemfc.nemweb import (
    CURRENT,
    NEM_TZ,
    NemwebClient,
)

log = logging.getLogger("verify")

AGGREGATED_CSV = (
    "https://www.aemo.com.au/aemo/data/nem/priceanddemand/PRICE_AND_DEMAND_{ym}_{region}.csv"
)

UNRESOLVED = "UNRESOLVED"


class Report:
    """Accumulates findings so a failure in one section does not lose the rest."""

    def __init__(self) -> None:
        self.sections: list[tuple[str, list[str]]] = []

    def section(self, title: str) -> list[str]:
        body: list[str] = []
        self.sections.append((title, body))
        return body

    def render(self, generated_at: datetime) -> str:
        stamp = generated_at.strftime("%d %b %Y %H:%M timezone.utc")
        out = [
            "# Day 1 — MMS format findings",
            "",
            f"Generated by `scripts/verify_formats.py` on {stamp} against live NEMWeb files.",
            "Every statement below came from parsing a downloaded file, not from documentation.",
            "",
        ]
        for title, body in self.sections:
            out.append(f"## {title}")
            out.append("")
            out.extend(body)
            out.append("")
        return "\n".join(out)


def _fmt(dt: datetime | None) -> str:
    if dt is None:
        return UNRESOLVED
    return dt.astimezone(NEM_TZ).strftime("%Y-%m-%d %H:%M:%S AEST")


def _table_block(parsed: MMSFile) -> list[str]:
    inv = parsed.inventory()
    lines = ["| namespace | table | version | rows | columns |", "|---|---|---|---|---|"]
    for _, r in inv.iterrows():
        lines.append(
            f"| {r['namespace']} | {r['table']} | {r['version']} | {r['rows']} | {r['columns']} |"
        )
    return lines


def check_publish_lag(client: NemwebClient, report: Report) -> None:
    """Measure the gap between generation and publication for P5MIN."""
    body = report.section("P5MIN publication lag")
    entries = client.list_directory(f"{CURRENT}/P5_Reports/")
    lags = [(e, e.publish_lag.total_seconds() / 60) for e in entries if e.publish_lag is not None]
    if not lags:
        body.append(
            "Could not measure: no P5MIN filename carried a parseable generation timestamp."
        )
        return

    values = [m for _, m in lags]
    worst_entry, worst = max(lags, key=lambda t: t[1])
    body += [
        f"Sampled {len(values)} files currently listed in `Reports/Current/P5_Reports/`.",
        "",
        "| statistic | minutes between generation and appearing on the site |",
        "|---|---|",
        f"| median | {statistics.median(values):.1f} |",
        f"| 90th percentile | {sorted(values)[int(0.9 * (len(values) - 1))]:.1f} |",
        f"| maximum | {worst:.1f} |",
        "",
        f"Slowest file: `{worst_entry.filename}`, generated "
        f"{_fmt(worst_entry.generated_at_utc)}, listed {_fmt(worst_entry.listed_at_utc)}.",
        "",
        "**Consequence for the feature layer.** AEMO's pre-dispatch forecast is both a model",
        "feature and the benchmark the project is measured against, so an as-of join keyed on",
        "the generation timestamp would let the model read a forecast before it was published,",
        "on exactly the comparison the project rests on. Join on `known_at`, which is the later",
        "of the generation timestamp and the directory listing time.",
        "",
        "One caveat worth recording rather than glossing: the directory index timestamp has",
        "minute granularity and is assumed to be NEM time. It is an upper bound on availability,",
        "not a measurement of it, which is the safe direction to be wrong in.",
    ]


def check_dispatchis(client: NemwebClient, data_dir: Path, region: str, report: Report):
    """Parse a live DISPATCHIS file and resolve the timestamp convention."""
    body = report.section("DISPATCHIS layout")
    entry = client.latest(f"{CURRENT}/DispatchIS_Reports/")
    path = client.download(entry, data_dir / "verify")
    parsed = read_mms_zip_single(path)

    body += [
        f"File: `{entry.filename}` ({entry.size_bytes} bytes)",
        f"Filename interval label: {_fmt(entry.interval_label_utc)}",
        f"Listed on NEMWeb at: {_fmt(entry.listed_at_utc)}",
        f"C header generated at: "
        f"{_fmt(parsed.header.generated_at_local.replace(tzinfo=NEM_TZ)) if parsed.header.generated_at_local else UNRESOLVED}",
        f"Footer row count matches parsed rows: {parsed.row_count_matches}",
        "",
        "Tables present:",
        "",
    ]
    body += _table_block(parsed)
    body.append("")

    try:
        price = parsed.get("PRICE", namespace="DISPATCH")
    except KeyError as exc:
        body.append(f"**{UNRESOLVED}**: {exc}")
        return parsed, entry, None

    body += [f"`DISPATCH.PRICE` columns: `{'`, `'.join(price.columns)}`", ""]

    settlement = price["SETTLEMENTDATE"].iloc[0] if "SETTLEMENTDATE" in price else None
    body += [
        "### Timestamp convention",
        "",
        f"- Filename label: `{entry.filename.split('_')[2]}`",
        f"- First `SETTLEMENTDATE` in the file: `{settlement}`",
        f"- File appeared on NEMWeb at: {_fmt(entry.listed_at_utc)}",
        "",
    ]
    if settlement and entry.listed_at_utc:
        try:
            sd = datetime.strptime(str(settlement), "%Y/%m/%d %H:%M:%S").replace(tzinfo=NEM_TZ)
            delta = (entry.listed_at_utc - sd).total_seconds() / 60
            body.append(
                f"The file was listed {delta:+.0f} minutes relative to its own SETTLEMENTDATE."
            )
            if delta < 0:
                body += [
                    "",
                    "The file appears **before** the timestamp it carries. Under the",
                    "interval-ending convention a settled price cannot be published before its",
                    "interval has finished, so either the label is interval-beginning here, or",
                    "the published value is a dispatch solution for the interval about to run.",
                    "Section 5 below settles this by reconciling against the aggregated series.",
                ]
            else:
                body.append("")
                body.append(
                    "The file appears after its own SETTLEMENTDATE, consistent with the "
                    "interval-ending convention."
                )
        except ValueError:
            body.append(f"Could not parse SETTLEMENTDATE `{settlement}`.")

    body += ["", "### Intervention and price variants", ""]
    if "INTERVENTION" in price.columns:
        counts = price["INTERVENTION"].value_counts().to_dict()
        body.append(f"`INTERVENTION` present, values in this file: `{counts}`")
        body.append("")
        body.append(
            "When AEMO intervenes in the market it solves dispatch twice, once physically and "
            "once for pricing, and both solutions can appear for the same interval. Staging must "
            "filter to a single run rather than averaging them."
        )
    else:
        body.append("No `INTERVENTION` column in this file's `DISPATCH.PRICE`.")

    variants = [c for c in ("RRP", "ROP", "RAISE6SECRRP") if c in price.columns]
    body.append("")
    body.append(f"Price columns available: `{'`, `'.join(variants)}`")
    if "ROP" in price.columns and "RRP" in price.columns:
        body.append("")
        body.append(
            "`RRP` is the regional reference price used for settlement; `ROP` is the price "
            "originally produced by the solve before any intervention adjustment. The label "
            "must come from `RRP`."
        )

    if "REGIONID" in price.columns:
        row = price[price["REGIONID"] == region]
        if not row.empty:
            shown = row.iloc[0].to_dict()
            keep = {
                k: v
                for k, v in shown.items()
                if k
                in {
                    "SETTLEMENTDATE",
                    "RUNNO",
                    "REGIONID",
                    "DISPATCHINTERVAL",
                    "INTERVENTION",
                    "RRP",
                    "ROP",
                    "APCFLAG",
                    "MARKETSUSPENDEDFLAG",
                }
            }
            body += ["", f"### {region} row from this file", "", "```", str(keep), "```"]

    return parsed, entry, price


def check_p5min(client: NemwebClient, data_dir: Path, region: str, report: Report) -> None:
    """Confirm P5MIN carries the two timestamps the benchmark join needs."""
    body = report.section("P5MIN layout and the as-of join")
    entry = client.latest(f"{CURRENT}/P5_Reports/")
    path = client.download(entry, data_dir / "verify")
    parsed = read_mms_zip_single(path)

    body += [
        f"File: `{entry.filename}` ({entry.size_bytes} bytes)",
        f"Run label: {_fmt(entry.interval_label_utc)}",
        f"Generated at: {_fmt(entry.generated_at_utc)}",
        f"Listed at: {_fmt(entry.listed_at_utc)}",
        "",
        "Tables present:",
        "",
    ]
    body += _table_block(parsed)
    body.append("")

    target = None
    for key, df in parsed.tables.items():
        cols = {c.upper() for c in df.columns}
        if {"RUN_DATETIME", "INTERVAL_DATETIME"} <= cols and "RRP" in cols:
            target = (key, df)
            break

    if target is None:
        body += [
            f"**{UNRESOLVED}**: no table carried RUN_DATETIME, INTERVAL_DATETIME and RRP",
            "together. The benchmark join in the plan assumes that pair exists. If this stays",
            "unresolved, section 2.1's third baseline needs redesigning before Day 5.",
        ]
        return

    key, df = target
    body += [
        f"Benchmark table: `{key}`",
        f"Columns: `{'`, `'.join(df.columns)}`",
        "",
    ]

    runs = sorted(set(df["RUN_DATETIME"]))
    horizons = sorted(set(df["INTERVAL_DATETIME"]))
    body += [
        f"Distinct RUN_DATETIME values in the file: {len(runs)} — `{runs[:3]}`",
        f"Forecast intervals covered: {len(horizons)}, from `{horizons[0]}` to `{horizons[-1]}`",
        "",
        "Each file is one run forecasting a block of future intervals, which is the shape the",
        "as-of join needs: for a prediction at time t, take the latest run whose `known_at` is",
        "at or before t, then read its row for the target interval.",
        "",
    ]

    if "REGIONID" in df.columns:
        sub = df[df["REGIONID"] == region][
            [
                c
                for c in ("RUN_DATETIME", "INTERVAL_DATETIME", "RRP", "TOTALDEMAND")
                if c in df.columns
            ]
        ]
        body += [
            f"### {region} forecast rows (first five)",
            "",
            "```",
            sub.head().to_string(index=False),
            "```",
        ]


def check_reconciliation(client: NemwebClient, data_dir: Path, region: str, report: Report) -> None:
    """Reconcile parsed 5-minute prices against AEMO's aggregated series.

    This is the check that makes Day 1's exit condition testable. Matching a
    column name proves nothing; matching a number AEMO published through a
    different pipeline proves the right column was read, and the alignment that
    makes it match also settles the interval-labelling question.
    """
    body = report.section("Reconciliation against the aggregated price series")

    entries = [
        e
        for e in client.list_directory(f"{CURRENT}/DispatchIS_Reports/")
        if e.interval_label_utc is not None
    ]
    if not entries:
        body.append(f"**{UNRESOLVED}**: no DISPATCHIS files listed.")
        return
    entries.sort(key=lambda e: e.interval_label_utc)  # type: ignore[arg-type,return-value]

    latest_local = entries[-1].interval_label_utc.astimezone(NEM_TZ)  # type: ignore[union-attr]
    ym = latest_local.strftime("%Y%m")
    url = AGGREGATED_CSV.format(ym=ym, region=region)
    try:
        response = httpx.get(url, timeout=90.0, follow_redirects=True)
        response.raise_for_status()
        agg = pd.read_csv(io.BytesIO(response.content))
    except Exception as exc:
        body.append(f"**{UNRESOLVED}**: could not read `{url}` ({exc}).")
        return

    agg["SETTLEMENTDATE"] = pd.to_datetime(agg["SETTLEMENTDATE"])
    agg = agg.sort_values("SETTLEMENTDATE")
    spacing = agg["SETTLEMENTDATE"].diff().dropna().mode()
    spacing_min = int(spacing.iloc[0].total_seconds() // 60) if not spacing.empty else 0
    body += [
        f"Aggregated series: `{url}`",
        f"Rows: {len(agg)}, covering {agg['SETTLEMENTDATE'].min()} to {agg['SETTLEMENTDATE'].max()}",
        f"Detected interval spacing: {spacing_min} minutes",
        "",
    ]

    # Find the most recent aggregated period fully covered by files still in
    # Reports/Current, which holds roughly two days.
    have = {e.interval_label_utc.astimezone(NEM_TZ).replace(tzinfo=None): e for e in entries}  # type: ignore[union-attr]
    if not have:
        body.append(f"**{UNRESOLVED}**: no usable interval labels.")
        return

    per_period = max(1, spacing_min // 5)
    candidate = None
    for _, agg_row in agg.iloc[::-1].iterrows():
        end = agg_row["SETTLEMENTDATE"].to_pydatetime()
        # Try both readings of the aggregated timestamp.
        for label, offsets in (
            ("interval-ending", [end - timedelta(minutes=5 * i) for i in range(per_period)]),
            (
                "interval-beginning",
                [end + timedelta(minutes=5 * i) for i in range(per_period)],
            ),
        ):
            if all(o in have for o in offsets):
                candidate = (end, label, offsets, float(agg_row["RRP"]))
                break
        if candidate:
            break

    if candidate is None:
        body += [
            f"**{UNRESOLVED}**: the aggregated series does not yet overlap the files held in",
            "`Reports/Current` (about two days). Re-run once the aggregated series catches up,",
            "or repeat this check against `Reports/Archive/DispatchIS_Reports/` during the",
            "Day 2 backfill.",
        ]
        return

    end, alignment, offsets, published = candidate
    prices: list[float] = []
    for offset in sorted(offsets):
        entry = have[offset]
        parsed = read_mms_zip_single(client.download(entry, data_dir / "verify"))
        price = parsed.get("PRICE", namespace="DISPATCH")
        sel = price[price["REGIONID"] == region]
        if "INTERVENTION" in sel.columns:
            sel = sel[sel["INTERVENTION"] == "0"]
        if sel.empty:
            body.append(f"**{UNRESOLVED}**: no {region} non-intervention row in {entry.filename}.")
            return
        prices.append(float(sel["RRP"].iloc[0]))

    computed = sum(prices) / len(prices)
    diff = computed - published
    matched = abs(diff) < max(0.01, abs(published) * 1e-4)

    body += [
        f"Aggregated period ending `{end}`: published RRP **{published:.2f}** $/MWh",
        f"Mean of {len(prices)} parsed 5-minute RRP values: **{computed:.2f}** $/MWh",
        f"Difference: {diff:+.4f}",
        f"Alignment that reconciles: **{alignment}**",
        "",
        f"Parsed values: `{[round(p, 2) for p in prices]}`",
        "",
    ]
    if matched:
        body += [
            "**Reconciled.** The parser reads the settlement price AEMO publishes, and the",
            f"aggregated timestamp is {alignment}. Every downstream lag is defined against this.",
        ]
    else:
        body += [
            "**Did not reconcile.** Do not proceed to Day 2 until this is understood: either the",
            "wrong column is being read, intervention rows are being mixed in, or the interval",
            "alignment is different from both readings tried here.",
        ]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--region", default=None)
    parser.add_argument("--out", default=None)
    args = parser.parse_args()

    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(name)s %(message)s")
    settings = load_settings()
    region = args.region or settings.region
    out = Path(args.out) if args.out else REPO_ROOT / "docs" / "day1_format_findings.md"

    report = Report()
    data_dir = settings.data_dir

    with NemwebClient(settings.user_agent) as client:
        for name, fn in (
            ("publish lag", lambda: check_publish_lag(client, report)),
            ("DISPATCHIS", lambda: check_dispatchis(client, data_dir, region, report)),
            ("P5MIN", lambda: check_p5min(client, data_dir, region, report)),
            ("reconciliation", lambda: check_reconciliation(client, data_dir, region, report)),
        ):
            try:
                fn()
            except Exception as exc:
                log.exception("%s check failed", name)
                report.section(f"{name} — failed")[:] = [f"```\n{exc!r}\n```"]

    out.parent.mkdir(parents=True, exist_ok=True)
    text = report.render(datetime.now(timezone.utc))
    out.write_text(text, encoding="utf-8")
    print(text)
    print(f"\nWritten to {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
